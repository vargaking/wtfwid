import { mkdtemp, readFile, stat, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { buildGraph } from '../graph';
import type { Issue, PullDigest, PullRequest, Snapshot } from '../model';
import { cloudSessions, pullAsDigest, pullKey, relationsOf } from '../relations';
import { fetchPullDigest, RateLimited, sessionLinks, toPullRequest } from './github';
import { createPullIndex } from './pulls';
import { withDigests } from './related';

const A = 'https://claude.ai/code/session_01AAAAaaaa';
const B = 'https://claude.ai/code/session_01BBBBbbbb';
const json = (body: unknown, status = 200, headers: Record<string, string> = {}) => new Response(JSON.stringify(body), { status, headers });
const pr = (number: number, over: Partial<PullRequest> = {}): PullRequest => ({
	repo: 'Acme/App', number, title: `ENG-${number} change`, url: `https://github.com/Acme/App/pull/${number}`, branch: `fix/eng-${number}-thing`, state: 'merged',
	createdAt: `2026-10-0${number}T09:00:00Z`, updatedAt: `2026-10-0${number}T12:00:00Z`, ...over
});
const digest = (over: Partial<PullDigest> = {}): PullDigest => ({ stamp: '', readAt: 0, files: [], added: 0, removed: 0, commits: [], sessions: [], ...over });
const min = (iso: string) => Date.parse(iso) / 60_000;

describe('what a pull request says about the session that made it', () => {
	it('S-90: finds the session links in a description, each once', () => {
		expect(sessionLinks(`Fixes the thing.\n\n${A}\n\n---\n_Generated by [Claude Code](${A})_ and ${B}.`)).toEqual([A, B]);
		expect(sessionLinks('https://claude.ai/chat/123 and https://example.com/code/session_x')).toEqual([]);
		expect(sessionLinks(null)).toEqual([]);
		expect(toPullRequest('o/r', { number: 7, title: 't', html_url: 'u', head: { ref: 'b' }, state: 'open', created_at: 'c', updated_at: 'd', body: `x\n${A}` })).toMatchObject({ updatedAt: 'd', sessions: [A] });
		// nothing to say: the fields are left out, not empty
		expect(toPullRequest('o/r', { number: 7, title: 't', html_url: 'u', head: { ref: 'b' }, state: 'open', created_at: 'c', body: null })).not.toHaveProperty('sessions');
	});

	it('S-56, S-90: reads a pull request\'s files and commits, with the session each commit names', async () => {
		const asked: { url: string; auth: string | null }[] = [];
		const fetcher = (async (url: string, init: RequestInit) => {
			asked.push({ url, auth: new Headers(init.headers).get('authorization') });
			if (url.includes('/files')) return json([{ filename: 'src/a.ts', additions: 40, deletions: 2, changes: 42 }, { filename: 'README.md', additions: 1, deletions: 0, changes: 1 }, { nothing: true }]);
			return json([
				{ commit: { author: { date: '2026-10-02T10:30:00Z' }, message: `Second\n\nCo-Authored-By: Claude\nClaude-Session: ${B}` } },
				{ commit: { author: { date: '2026-10-02T09:00:00Z' }, message: `First\n\nClaude-Session: ${A}` } },
				{ commit: { author: { date: '2026-10-02T11:00:00Z' }, message: 'By hand' } },
				{ commit: { author: { date: 'not a date' }, message: 'broken' } }
			]);
		}) as typeof fetch;
		const out = await fetchPullDigest(pr(2), 'tok', 5, fetcher);
		expect(out).toEqual({
			stamp: '2026-10-02T12:00:00Z',
			readAt: 5,
			files: [{ path: 'src/a.ts', changes: 42 }, { path: 'README.md', changes: 1 }],
			added: 41,
			removed: 2,
			// in order of time; each with the session that made it, or -1
			commits: [[min('2026-10-02T09:00:00Z'), 1], [min('2026-10-02T10:30:00Z'), 0], [min('2026-10-02T11:00:00Z'), -1]],
			sessions: [B, A]
		});
		// two requests, both only reading, with the token
		expect(asked.map((a) => a.url)).toEqual(['https://api.github.com/repos/Acme/App/pulls/2/files?per_page=100&page=1', 'https://api.github.com/repos/Acme/App/pulls/2/commits?per_page=100&page=1']);
		expect(asked.every((a) => a.auth === 'Bearer tok')).toBe(true);
	});

	it('S-90: says so when GitHub asks to slow down, which is not the same as a pull request that is gone', async () => {
		const limited = (async () => json({}, 403, { 'x-ratelimit-remaining': '0' })) as unknown as typeof fetch;
		await expect(fetchPullDigest(pr(1), null, 0, limited)).rejects.toBeInstanceOf(RateLimited);
		const gone = (async () => json({}, 404)) as unknown as typeof fetch;
		await expect(fetchPullDigest(pr(1), null, 0, gone)).rejects.not.toBeInstanceOf(RateLimited);
	});
});

describe('the index of pull requests', () => {
	const home = () => mkdtemp(join(tmpdir(), 'wtfwid-pulls-'));

	it('S-56: reads each pull request once, again when GitHub says it changed, and keeps it for a fresh start', async () => {
		const dir = await home();
		const reads: number[] = [];
		const read = async (p: PullRequest) => (reads.push(p.number), digest({ stamp: p.updatedAt ?? '', files: [{ path: `f${reads.length}.ts`, changes: 1 }] }));
		const index = createPullIndex(dir, { read });
		const out = await index.digests([pr(1), pr(2)], 'tok');
		// most recently changed first
		expect(reads).toEqual([2, 1]);
		expect(Object.keys(out).sort()).toEqual(['acme/app#1', 'acme/app#2']);
		await index.digests([pr(1), pr(2)], 'tok');
		expect(reads).toHaveLength(2);

		await index.digests([pr(1, { updatedAt: '2026-10-09T00:00:00Z' }), pr(2)], 'tok');
		expect(reads).toEqual([2, 1, 1]);

		const file = join(dir, 'pulls.json');
		if (process.platform !== 'win32') expect((await stat(file)).mode & 0o777).toBe(0o600);
		const restarted = await createPullIndex(dir, { read }).digests([pr(1, { updatedAt: '2026-10-09T00:00:00Z' }), pr(2)], 'tok');
		expect(restarted['acme/app#1'].files[0].path).toBe('f3.ts');
		expect(reads).toHaveLength(3);
		// a broken file just means reading again
		await writeFile(file, 'not json');
		await createPullIndex(dir, { read }).digests([pr(2)], 'tok');
		expect(reads).toHaveLength(4);
		expect(JSON.parse(await readFile(file, 'utf8')).version).toBe(1);
	});

	it('S-56: a long history arrives a round at a time, and says when more is in', async () => {
		const dir = await home();
		let clock = 0;
		let reads = 0;
		const read = async (p: PullRequest) => (reads++, (clock += 400), digest({ stamp: p.updatedAt ?? '' }));
		const index = createPullIndex(dir, { read, now: () => clock, budgetMs: 1000, perPass: 6 });
		const prs = Array.from({ length: 9 }, (_, i) => pr(i + 1));
		let told = 0;
		const first = await index.digests(prs, 'tok', () => told++);
		// a few before answering, the rest of this round afterwards
		expect(Object.keys(first).length).toBeLessThan(6);
		await index.settled();
		expect(reads).toBe(6);
		expect(told).toBe(1);
		// the screen asks again, and the next round reads what is left
		const second = await index.digests(prs, 'tok', () => told++);
		await index.settled();
		expect(reads).toBe(9);
		expect(Object.keys(await index.digests(prs, 'tok', () => told++))).toHaveLength(9);
		expect(Object.keys(second).length).toBeGreaterThanOrEqual(6);
		// nothing left: nothing read, nobody told again
		const quiet = told;
		await index.digests(prs, 'tok', () => told++);
		await index.settled();
		expect(reads).toBe(9);
		expect(told).toBe(quiet);
	});

	it('S-56: a pull request that cannot be read is left alone for a while, and GitHub saying "slow down" stops everything', async () => {
		const dir = await home();
		let clock = 1_000_000;
		const asked: number[] = [];
		const read = async (p: PullRequest) => {
			asked.push(p.number);
			if (p.number === 2) throw new Error('HTTP 404');
			return digest({ stamp: p.updatedAt ?? '' });
		};
		const index = createPullIndex(dir, { read, now: () => clock });
		let told = 0;
		expect(Object.keys(await index.digests([pr(1), pr(2)], 'tok', () => told++))).toEqual(['acme/app#1']);
		// asking again does not hammer the one that failed, and does not ask for another round
		await index.digests([pr(1), pr(2)], 'tok', () => told++);
		await index.settled();
		expect(asked).toEqual([2, 1]);
		expect(told).toBe(0);
		clock += 31 * 60_000;
		await index.digests([pr(1), pr(2)], 'tok');
		expect(asked).toEqual([2, 1, 2]);

		const limited = createPullIndex(await home(), { read: async (p) => (asked.push(100 + p.number), Promise.reject(new RateLimited('slow down'))), now: () => clock });
		await limited.digests([pr(1), pr(2), pr(3)], 'tok');
		const after = asked.filter((n) => n > 100).length;
		expect(after).toBeLessThanOrEqual(4); // the ones already on their way when it said so
		await limited.digests([pr(1), pr(2), pr(3)], 'tok');
		expect(asked.filter((n) => n > 100)).toHaveLength(after);
		clock += 16 * 60_000;
		await limited.digests([pr(1)], 'tok');
		expect(asked.filter((n) => n > 100).length).toBeGreaterThan(after);
	});
});

describe('tickets related through their pull requests', () => {
	const issue = (n: number): Issue => ({
		id: `ENG-${n}`, title: `Ticket ${n}`, url: '', createdAt: '2026-10-01T08:00:00.000Z', startedAt: `2026-10-0${n}T09:00:00.000Z`, completedAt: null, canceledAt: null,
		stateName: 'In Progress', stateType: 'started', branchName: `fix/eng-${n}-thing`, project: { id: 'web', name: 'Web' }, milestone: null
	});
	const snapshot = (prs: PullRequest[]): Snapshot => ({ fetchedAt: '2026-10-10T12:00:00.000Z', demo: false, warnings: [], issues: [1, 2, 3, 4].map(issue), prs, sessions: [] });

	it('S-56: two tickets whose pull requests change the same file are related, with no session on this machine at all', () => {
		const snap = snapshot([pr(1), pr(2), pr(3)]);
		const graph = withDigests(buildGraph(snap), snap, {}, {
			[pullKey(pr(1))]: digest({ files: [{ path: 'src/voice/room.ts', changes: 30 }, { path: 'src/only-1.ts', changes: 2 }], added: 30, removed: 2, commits: [[min('2026-10-01T10:00:00Z'), -1]] }),
			[pullKey(pr(2))]: digest({ files: [{ path: 'src/voice/room.ts', changes: 4 }], added: 3, removed: 1, commits: [[min('2026-10-02T10:00:00Z'), -1], [min('2026-10-02T11:00:00Z'), -1]] }),
			[pullKey(pr(3))]: digest({ files: [{ path: 'src/other.ts', changes: 1 }] })
		});
		expect(graph.relations).toEqual([{ a: 'ENG-1', b: 'ENG-2', continued: false, weight: 1, shared: 1, files: ['src/voice/room.ts'] }]);
		const two = graph.lanes.flatMap((l) => l.nodes).find((n) => n.id === 'ENG-2')!;
		// S-88: what its pull requests hold is the work that can be counted for it
		expect(two.work).toMatchObject({ minutes: 0, sessions: 0, commits: [min('2026-10-02T10:00:00Z'), min('2026-10-02T11:00:00Z')], lines: { added: 3, removed: 1 } });
		// a ticket with no pull request read has no work to show
		expect(graph.lanes.flatMap((l) => l.nodes).find((n) => n.id === 'ENG-4')!.work).toBeUndefined();
	});

	it('S-90: the same file in two repositories is two files, and the same one in a repository and on this machine too', () => {
		const snap = snapshot([pr(1), pr(2, { repo: 'acme/other' })]);
		const graph = withDigests(buildGraph(snap), snap, {}, { [pullKey(pr(1))]: digest({ files: [{ path: 'src/index.ts', changes: 1 }] }), [pullKey(pr(2, { repo: 'acme/other' }))]: digest({ files: [{ path: 'src/index.ts', changes: 1 }] }) });
		expect(graph.relations).toEqual([]);
		expect(pullAsDigest(pr(1), digest()).root).toBe('github.com/acme/app');
	});

	it('S-90: a cloud session is put on the ticket through the link on its pull request, from the commits or the description', () => {
		const snap = snapshot([pr(1, { sessions: [A] }), pr(2), pr(3)]);
		const graph = withDigests(buildGraph(snap), snap, {}, { [pullKey(pr(2))]: digest({ sessions: [B], commits: [[1, 0]] }) });
		const nodes = Object.fromEntries(graph.lanes.flatMap((l) => l.nodes).map((n) => [n.id, n]));
		expect(nodes['ENG-1'].prs[0].sessions).toEqual([A]);
		expect(nodes['ENG-2'].prs[0].sessions).toEqual([B]);
		expect(nodes['ENG-3'].prs[0].sessions).toBeUndefined();
		expect(cloudSessions(nodes['ENG-2'])).toEqual([B]);
	});

	it('S-90: one cloud session that worked on several tickets is one line of work through them, in order', () => {
		const snap = snapshot([pr(3), pr(1), pr(2), pr(4)]);
		const graph = withDigests(buildGraph(snap), snap, {}, {
			[pullKey(pr(1))]: digest({ sessions: [A] }),
			[pullKey(pr(2))]: digest({ sessions: [A, B] }),
			[pullKey(pr(3))]: digest({ sessions: [A] }),
			[pullKey(pr(4))]: digest({ sessions: [B] })
		});
		expect(graph.threads).toEqual([
			{ session: A, nodes: ['ENG-1', 'ENG-2', 'ENG-3'] },
			{ session: B, nodes: ['ENG-2', 'ENG-4'] }
		]);
		// each step of the way is a relation, the way the session went
		expect(graph.relations!.map((r) => [r.a, r.b, r.continued])).toEqual([['ENG-1', 'ENG-2', true], ['ENG-2', 'ENG-3', true], ['ENG-2', 'ENG-4', true]]);
		expect(relationsOf(graph.relations, 'ENG-2').map((r) => r.other).sort()).toEqual(['ENG-1', 'ENG-3', 'ENG-4']);
	});
});
